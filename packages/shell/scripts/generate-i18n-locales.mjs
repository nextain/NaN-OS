import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import ts from "typescript";

const root = resolve(import.meta.dirname, "..");
const sourcePath = resolve(root, "scripts/i18n-translations.source.ts");
const outputDirectory = resolve(root, "src/lib/locales");
const source = readFileSync(sourcePath, "utf8");
const checkOnly = process.argv.includes("--check");
const transpiled = ts.transpileModule(source, {
	compilerOptions: {
		module: ts.ModuleKind.CommonJS,
		target: ts.ScriptTarget.ES2022,
	},
	fileName: sourcePath,
}).outputText;
const module = { exports: {} };
new Function("exports", "module", transpiled)(module.exports, module);
const { translations } = module.exports;

if (!translations || typeof translations !== "object") {
	throw new Error("i18n source did not export translations");
}

const locales = [
	"ko",
	"en",
	"ja",
	"zh",
	"fr",
	"de",
	"ru",
	"es",
	"ar",
	"hi",
	"bn",
	"pt",
	"id",
	"vi",
];

mkdirSync(outputDirectory, { recursive: true });

function emit(path, content) {
	if (checkOnly) {
		if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
			throw new Error(`generated locale is stale: ${path}`);
		}
		return;
	}
	writeFileSync(path, content);
}

for (const locale of locales) {
	const localized = Object.fromEntries(
		Object.entries(translations).map(([key, values]) => {
			const value = values[locale];
			if (typeof value !== "string") {
				throw new Error(`missing ${locale} translation for ${key}`);
			}
			return [key, value];
		}),
	);
	const content = `// Generated by scripts/generate-i18n-locales.mjs. Do not edit.\nexport default ${JSON.stringify(localized, null, "\t")} as const;\n`;
	emit(resolve(outputDirectory, `${locale}.ts`), content);
}

const keyModule = `// Generated by scripts/generate-i18n-locales.mjs. Do not edit.\nexport type TranslationKey = keyof typeof import("./en").default;\n`;
emit(resolve(outputDirectory, "keys.ts"), keyModule);

console.log(
	`${checkOnly ? "verified" : "generated"} ${locales.length} locales with ${Object.keys(translations).length} keys each in ${dirname(outputDirectory)}`,
);
